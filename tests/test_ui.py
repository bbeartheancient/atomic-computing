def test_tile_bounds_from_display():
    from atomic.tiles import Display
    d = Display(640, 480, cols=4, rows=4, frame_h=60)
    assert d.tile_w == 160
    assert d.tile_h == 105
    assert len(d.tiles) == 16
    for t in d.tiles:
        assert t.w == 160
        assert t.h == 105


def test_control_frame_schema():
    from atomic.ui.server import _control_schema
    from atomic.ui.programs import build
    from atomic.ui.viewer import Viewer
    prog = build("clock_counter")
    v = Viewer(prog, name="ctrl_test")
    schema = _control_schema(v)
    assert "params" in schema
    assert "taps" in schema
    assert len(schema["params"]) >= 1
    for p in schema["params"]:
        assert "module" in p
        assert "key" in p
        assert "min" in p
        assert "max" in p
        assert isinstance(p["value"], float)


