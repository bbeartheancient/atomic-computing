def test_viewer_param_feed():
    from atomic.ui.programs import build
    from atomic.ui.viewer import Viewer
    prog = build("clock_counter")
    v = Viewer(prog, name="test_param_feed")
    Viewer.put("test_param_feed", v)
    snap0 = v.batch(5)
    assert snap0["bus"].get("cnt.acc", 0) >= 0
    v.set_param("clk", "bpm", 300.0)
    snap1 = v.batch(5)
    assert snap1["t"] == 10
    Viewer.delete("test_param_feed")


