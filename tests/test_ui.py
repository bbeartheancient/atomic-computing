def test_hadamard_wxyz_h4_rows():
    from atomic.ui.server import create_app
    from fastapi.testclient import TestClient
    app = create_app()
    client = TestClient(app)
    with client:
        r = client.post("/api/batch/hadamard_wxyz", json={"ticks": 5})
